// Generates supabase/migrations/20261126000003_seed_rules_and_privacy.sql from the app's own tables
// (src/lib/rulesets.ts, src/sync/outbox.ts), so server and client scoring/privacy cannot drift.
//   node scripts/db/gen-seed.mjs          write the file
//   node scripts/db/gen-seed.mjs --check  exit 1 if the committed file differs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const fs = require('node:fs');
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: 1, target: 9 } }).outputText, f);
const { RULESETS } = require('../../src/lib/rulesets.ts');
const { privacyFor } = require('../../src/sync/outbox.ts');
const { ACTIONS } = require('../../src/data/actions.ts');

let sql = '-- GENERATED by scripts/db/gen-seed.mjs from src/lib/rulesets.ts and src/sync/outbox.ts. Do not edit by hand.\n';
sql += 'insert into public.scoring_versions (version, blessing_goal_bonus) values\n' + Object.values(RULESETS).map((r) => `  ('${r.version}', ${r.blessingGoalBonus})`).join(',\n') + ';\n\n';
const rows = [];
for (const r of Object.values(RULESETS)) for (const [k, a] of Object.entries(r.actions)) rows.push(`  ('${r.version}', '${k}', ${a.points}, ${a.dailyCap}, ${!!a.oncePerDay}, ${!!a.refScoped}, ${a.minyanBonus ?? 0}, ${a.onTimeBonus ?? 0})`);
sql += 'insert into public.scoring_rules (version, action_type, points, daily_cap, once_per_day, ref_scoped, minyan_bonus, on_time_bonus) values\n' + rows.join(',\n') + ';\n\n';
sql += 'insert into public.action_privacy (action_type, cloud_backup, social) values\n' + Object.keys(ACTIONS).map((k) => { const p = privacyFor(k); return `  ('${k}', ${p.cloudBackup}, ${p.social})`; }).join(',\n') + ';\n';

const path = 'supabase/migrations/20261126000003_seed_rules_and_privacy.sql';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) {
    console.error(`${path} is out of date: run node scripts/db/gen-seed.mjs`);
    process.exit(1);
  }
  console.log('Seed check passed: server rules and privacy match the app');
} else {
  writeFileSync(path, sql);
  console.log(`wrote ${path}`);
}
